import fs from 'node:fs/promises';
import { build } from 'esbuild';
import { createRequire } from 'node:module';

// Project the actual registry, including composed fields, without duplicating
// module definitions in the Edge Function. No tenant data is exported.
const result = await build({
  entryPoints: ['utils/aiRecordCreation.ts'], bundle: true, write: false,
  platform: 'node', format: 'cjs', packages: 'external', logLevel: 'silent',
  define: { 'import.meta.env': '{}' },
  plugins: [{ name: 'offline-schema-export', setup(builder) {
    builder.onResolve({ filter: /supabaseClient$/ }, () => ({ path: 'supabase-client', namespace: 'offline' }));
    builder.onLoad({ filter: /.*/, namespace: 'offline' }, () => ({ contents: 'export const supabase = null; export const supabasePublic = null; export const SUPABASE_URL = ""; export const SUPABASE_ANON_KEY = "";' }));
  } }],
});
const exported = { exports: {} };
new Function('require', 'module', 'exports', result.outputFiles[0].text)(createRequire(import.meta.url), exported, exported.exports);
{
  const { buildAiRecordCreationSchema, buildAiRecordModuleOptions } = exported.exports;
  const schemas = Object.fromEntries(buildAiRecordModuleOptions().map(({ value }) => {
    const { contextFields, ...schema } = buildAiRecordCreationSchema(value);
    return [value, { ...schema, contextFields: contextFields.filter((field) => field.aiWritable === false || field.readonly).map(({ key, aiWritable, readonly }) => ({ key, aiWritable, readonly })) }];
  }));
  const output = `// Generated by scripts/export-ai-record-schemas.mjs; do not edit.\nexport const AI_RECORD_SCHEMAS = ${JSON.stringify(schemas)} as const;\n`;
  const target = new URL('../supabase/functions/_shared/ai-record-schemas.generated.ts', import.meta.url);
  if (process.argv.includes('--check')) {
    if (await fs.readFile(target, 'utf8') !== output) throw new Error('AI record schemas are stale; run npm run ai:schemas');
  } else {
    await fs.writeFile(target, output, 'utf8');
  }
}
// Ship the canonical form policy to Edge Functions without outside-root imports.
const policy = await build({ stdin: { contents: 'export { resolveConditionalFieldState } from "./utils/conditionalFieldRules.ts";', resolveDir: process.cwd() }, bundle: true,
  write: false, platform: 'neutral', format: 'esm', target: 'es2022', logLevel: 'silent' });
const policyOutput = '// @ts-nocheck\n// Generated from utils/conditionalFieldRules.ts; do not edit.\n' + policy.outputFiles[0].text;
const policyTarget = new URL('../supabase/functions/_shared/ai-field-policy.generated.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (await fs.readFile(policyTarget, 'utf8') !== policyOutput) throw new Error('AI field policy is stale; run npm run ai:schemas');
} else await fs.writeFile(policyTarget, policyOutput, 'utf8');
