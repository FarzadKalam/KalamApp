begin;
-- Private runtime state. Only controlled Edge handlers and the platform voice worker access it.
create table if not exists public.voip_ai_sessions(
 id uuid primary key default gen_random_uuid(),
 org_id uuid not null references public.organizations(id),
 requested_by uuid not null references public.profiles(id),
 account_id uuid not null references public.voip_external_accounts(id),
 bridge_id uuid references public.voip_provider_bridges(id),
 phone text not null,
 join_code text not null default (floor(random()*9000000000000000+1000000000000000)::bigint)::text,
 status text not null default 'queued' check(status in ('queued','preparing','dialing','active','completed','failed','cancelled')),
 purpose text not null default '',
 model_overrides jsonb not null default '{}'::jsonb,
 target_module text,
 target_record_id uuid,
 identity_verified boolean not null default false,
 pin_attempts integer not null default 0,
 channel_name text,
 failure_code text,
 created_at timestamptz not null default now(),
 started_at timestamptz,
 ended_at timestamptz,
 heartbeat_at timestamptz,
 max_duration_seconds integer not null default 180,
 unique(org_id,join_code)
);
create unique index if not exists uq_voip_ai_active_account on public.voip_ai_sessions(account_id)
 where status in ('queued','preparing','dialing','active');
create index if not exists idx_voip_ai_session_org_recent on public.voip_ai_sessions(org_id,created_at desc,id);
create index if not exists idx_voip_ai_session_queue on public.voip_ai_sessions(status,created_at);
create table if not exists public.voip_ai_session_events(
 id bigint generated by default as identity primary key,
 org_id uuid not null references public.organizations(id),
 session_id uuid not null references public.voip_ai_sessions(id) on delete cascade,
 kind text not null check(kind in ('customer','assistant','operator_note','system')),
 content text not null,
 created_by uuid references public.profiles(id),
 created_at timestamptz not null default now()
);
create index if not exists idx_voip_ai_event_org_session on public.voip_ai_session_events(org_id,session_id,id);
alter table public.voip_ai_sessions enable row level security;
alter table public.voip_ai_session_events enable row level security;
revoke all on public.voip_ai_sessions,public.voip_ai_session_events from public,anon,authenticated;
grant select,insert,update,delete on public.voip_ai_sessions,public.voip_ai_session_events to service_role;
grant usage,select on sequence public.voip_ai_session_events_id_seq to service_role;
-- Platform worker health is operational, not tenant content; clients get no table access.
create table if not exists public.voip_ai_worker_health(id text primary key,checked_at timestamptz not null default now());
alter table public.voip_ai_worker_health enable row level security;
revoke all on public.voip_ai_worker_health from public,anon,authenticated;
grant select,insert,update,delete on public.voip_ai_worker_health to service_role;
notify pgrst,'reload schema';
commit;
